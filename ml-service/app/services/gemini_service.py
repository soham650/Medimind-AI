import os
import requests
import json
from typing import List, Dict, Any

GEMINI_API_KEY = os.environ.get("GEMINI_API_KEY", "")
GEMINI_MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash-lite")
GEMINI_API_URL = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent"

SYSTEM_INSTRUCTION = (
    "You are a health assistant, not a doctor. Always recommend consulting a professional "
    "for serious symptoms. Never provide definitive diagnoses."
)

def get_gemini_chat_reply(message: str, history: List[Dict[str, Any]] = None) -> str:
    """
    Calls the Gemini API to get a chat response, enforcing clinical guardrails.
    """
    if not GEMINI_API_KEY:
        return "Gemini API key is not configured. Please set the GEMINI_API_KEY environment variable."

    contents = []
    if history:
        for msg in history:
            role = "user" if msg.get("sender") == "patient" else "model"
            contents.append({
                "role": role,
                "parts": [{"text": msg.get("text", "")}]
            })
    
    # Append the current message
    contents.append({
        "role": "user",
        "parts": [{"text": message}]
    })

    payload = {
        "contents": contents,
        "systemInstruction": {
            "parts": [{"text": SYSTEM_INSTRUCTION}]
        }
    }

    try:
        response = requests.post(
            f"{GEMINI_API_URL}?key={GEMINI_API_KEY}",
            json=payload,
            headers={"Content-Type": "application/json"},
            timeout=10
        )
        if response.status_code == 200:
            res_json = response.json()
            candidates = res_json.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text", "")
            return "No response generated by AI."
        else:
            return f"Error from Gemini API: {response.status_code} - {response.text}"
    except Exception as e:
        return f"Failed to connect to AI assistant: {str(e)}"


def analyze_report_with_gemini(file_name: str, file_type: str, file_data: str) -> dict:
    """
    Uses the Gemini API to perform clinical OCR and structure report parameters.
    """
    # 1. Parse base64 string from data URI if needed
    base64_str = file_data
    mime_type = file_type
    
    if "," in file_data:
        header, base64_str = file_data.split(",", 1)
        if ";" in header:
            part0 = header.split(";")[0]
            if ":" in part0:
                mime_type = part0.split(":")[1]

    # Provide a default mime type if missing
    if not mime_type:
        mime_type = "application/pdf" if file_name.lower().endswith(".pdf") else "image/png"

    # Define the default fallback response
    fallback_response = {
        "patientName": "Rahul Sharma",
        "reportDate": "2026-07-11",
        "summary": "Mock Report Analysis: The current blood panel demonstrates normal Hemoglobin with stable platelet and white blood cell counts.",
        "parameters": [
            {"name": "Hemoglobin", "value": 14.2, "unit": "g/dL", "range": "13.5 - 17.5", "status": "Normal"},
            {"name": "Platelets", "value": 210, "unit": "10³/µL", "range": "150 - 450", "status": "Normal"},
            {"name": "WBC Count", "value": 6.8, "unit": "10³/µL", "range": "4.5 - 11.0", "status": "Normal"}
        ]
    }

    if not GEMINI_API_KEY:
        # If API key is not configured, return the fallback mock
        return fallback_response

    prompt = (
        "Extract structured clinical metrics from this medical lab report. "
        "Locate patient name, report date, and key lab test parameters. "
        "For each parameter, extract the parameter name, result value, units, reference range, "
        "and calculate status as 'High', 'Low', or 'Normal' based on the reference range. "
        "Provide a brief clinical summary of the findings in 1-2 sentences. "
        "Return the output strictly as a JSON object matching this schema:\n"
        "{\n"
        "  \"patientName\": \"string\",\n"
        "  \"reportDate\": \"YYYY-MM-DD\",\n"
        "  \"summary\": \"string description\",\n"
        "  \"parameters\": [\n"
        "    {\n"
        "      \"name\": \"string\",\n"
        "      \"value\": float,\n"
        "      \"unit\": \"string\",\n"
        "      \"range\": \"string\",\n"
        "      \"status\": \"High\" | \"Low\" | \"Normal\"\n"
        "    }\n"
        "  ]\n"
        "}"
    )

    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt},
                    {
                        "inlineData": {
                            "mimeType": mime_type,
                            "data": base64_str
                        }
                    }
                ]
            }
        ],
        "generationConfig": {
            "responseMimeType": "application/json"
        }
    }

    try:
        response = requests.post(
            f"{GEMINI_API_URL}?key={GEMINI_API_KEY}",
            json=payload,
            headers={"Content-Type": "application/json"},
            timeout=25
        )
        if response.status_code == 200:
            res_json = response.json()
            candidates = res_json.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    text_out = parts[0].get("text", "").strip()
                    # Parse extracted JSON text
                    try:
                        parsed_dict = json.loads(text_out)
                        # Ensure required fields are present
                        if "patientName" in parsed_dict and "parameters" in parsed_dict:
                            return parsed_dict
                    except Exception as json_err:
                        print("Error parsing Gemini JSON response:", json_err)
        
        print(f"Gemini API returned status {response.status_code}. Details: {response.text}")
        return fallback_response
    except Exception as e:
        print("Failed to run Gemini report analysis:", e)
        return fallback_response
