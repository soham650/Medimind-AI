import { mlApi } from '../lib/mlApi';
import { supabase } from '../lib/supabaseClient';

/**
 * Core Service 1: AI Symptom Checker & Triage Engine
 * Performs symptom intake, risk classification (Low/Moderate/High),
 * disease prediction, and logs triage sessions to Supabase.
 */
export const triageService = {
  // Fetch master list of symptoms
  async getSymptomsList() {
    try {
      const data = await mlApi.getSymptoms();
      return data?.symptoms || [];
    } catch (err) {
      console.warn('Fallback symptoms list used:', err.message);
      return [
        'fever', 'cough', 'fatigue', 'headache', 'chest pain',
        'shortness of breath', 'joint pain', 'nausea', 'dizziness',
        'sore throat', 'loss of smell', 'abdominal pain', 'skin rash'
      ];
    }
  },

  // Predict disease and determine risk classification (Low / Moderate / High)
  async analyzeSymptoms(symptoms, userId = null) {
    const predictionResult = await mlApi.predictDisease(symptoms);
    
    // Determine risk classification based on predicted condition and severity
    let riskLevel = 'Low';
    const topProbability = predictionResult?.top_predictions?.[0]?.probability || 50;
    const diseaseName = (predictionResult?.top_predictions?.[0]?.disease || '').toLowerCase();

    const highRiskKeywords = ['pneumonia', 'cardiac', 'heart', 'stroke', 'sepsis', 'severe', 'acute respiratory'];
    const moderateRiskKeywords = ['covid', 'typhoid', 'dengue', 'malaria', 'migraine', 'hypertension'];

    if (highRiskKeywords.some(k => diseaseName.includes(k)) || topProbability > 85) {
      riskLevel = 'High';
    } else if (moderateRiskKeywords.some(k => diseaseName.includes(k)) || topProbability > 65) {
      riskLevel = 'Moderate';
    }

    // Persist to symptom_logs and predictions table if userId provided
    if (userId) {
      try {
        const { data: logData, error: logError } = await supabase
          .from('symptom_logs')
          .insert({ profile_id: userId, symptoms })
          .select()
          .single();

        if (!logError && logData) {
          const top = predictionResult?.top_predictions?.[0] || { disease: 'Undetermined', probability: 50 };
          await supabase.from('predictions').insert({
            profile_id: userId,
            symptom_log_id: logData.id,
            disease: top.disease,
            probability: top.probability,
            confidence_tag: riskLevel === 'High' ? 'High' : (riskLevel === 'Moderate' ? 'Medium' : 'Low')
          });
        }
      } catch (err) {
        console.error('Failed to log symptom session:', err);
      }
    }

    return {
      ...predictionResult,
      riskLevel,
      disclaimer: "This triage analysis is generated by MediMind AI for clinical decision support. Always consult a verified medical specialist for definitive treatment."
    };
  }
};
